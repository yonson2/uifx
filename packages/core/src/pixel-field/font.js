/**
 * Renders text into a bitmap of "1" (ink) and "0" rows.
 * Each font pixel becomes a `scale` x `scale` block; letters are `gap` font pixels apart.
 * @returns {{ rows: string[], width: number, height: number }}
 */
export function textToBitmap(text, { scale = 2, gap = 1 } = {}) {
  const glyphs = Array.from(text.toUpperCase(), (ch) => GLYPHS[ch] ?? GLYPHS[" "]);
  const rows = [];
  for (let y = 0; y < 7; y++) {
    const line = glyphs.map((g) => g[y]).join(".".repeat(gap));
    const scaled = Array.from(line, (px) => (px === "#" ? "1" : "0").repeat(scale)).join("");
    for (let k = 0; k < scale; k++) rows.push(scaled);
  }
  return { rows, width: rows[0]?.length ?? 0, height: rows.length };
}

/** Accepts a bitmap as rows of "1"/"0" (or "#"/"."). */
export function parseBitmap(lines) {
  const rows = lines.map((line) => line.replace(/[#xX]/g, "1").replace(/[^1]/g, "0"));
  const width = Math.max(...rows.map((r) => r.length));
  return { rows: rows.map((r) => r.padEnd(width, "0")), width, height: rows.length };
}
